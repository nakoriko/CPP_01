// 1. **Понимание ссылок и указателей:**
//    - Ссылка — всегда валидна, не может быть пустой.
//    - Указатель — может быть пустым, требует проверки перед использованием.

// 2. **Демонстрация разницы:**
//    - HumanA всегда вооружён (ссылка).
//    - HumanB может быть безоружным (указатель).

// 3. **Общий объект оружия:**
//    - Оба класса могут ссылаться/указывать на один и тот же объект Weapon.
//    - Если изменить тип оружия через setType, оба "человека" увидят изменение.

// 4. **Безопасность:**
//    - HumanB::attack() проверяет, есть ли оружие (weapon != 0).
//    - HumanA::attack() не требует проверки, weapon всегда валиден.


// - **Ссылка** — для обязательного, всегда существующего объекта.
// - **Указатель** — для опционального, возможно отсутствующего объекта.
// - Это классический пример, чтобы почувствовать разницу между этими двумя инструментами C++ и научиться выбирать подходящий в зависимости от задачи.

